    // SDK mirror for the output tree: the SDK co-locates only non-framework (NuGet/local) runtime
    // assemblies next to the app in bin/. Everything that ships in a shared framework is resolved
    // from the installed runtime at run time and is never copied; analyzer/generator DLLs are
    // compile-time only. Returns the subset of merged run references that the produced app actually
    // needs beside its own dll/pdb/runtimeconfig/apphost.
    public static List<string> GetOutputRuntimeFiles(IEnumerable<MetadataReference> mergedRunReferences,
        string projectRootPath, string targetFramework)
    {
        var frameworkNames = SharedFrameworkAssemblyNames(projectRootPath, targetFramework);
        var output = new List<string>();
        foreach (var reference in mergedRunReferences)
        {
            var display = reference.Display;
            if (string.IsNullOrEmpty(display)) continue;
            if (frameworkNames.Contains(Path.GetFileName(display))) continue;
            output.Add(display);
        }
        return output;
    }

    // File-name set of the assemblies shipped in the shared frameworks the app actually references.
    // Mirrors the SDK: only the frameworks listed in the restored assets (frameworkReferences) - i.e.
    // Microsoft.NETCore.App plus any explicit <FrameworkReference> like Microsoft.AspNetCore.App -
    // suppress copy-local. Enumerating every installed shared framework would wrongly drop assemblies
    // that an AspNetCore shared framework happens to carry (e.g. Microsoft.Extensions.*) from an app
    // that targets the console SDK and does not reference them. The exclusion is version-agnostic:
    // file names are stable across patches of the same framework, and the app resolves whatever the
    // targeted runtime provides at run time.
    private static HashSet<string> SharedFrameworkAssemblyNames(string projectRootPath, string targetFramework)
    {
        var names = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        try
        {
            var assetsPath = Path.Combine(projectRootPath, "obj", "project.assets.json");
            var frameworkNames = new List<string>();
            if (File.Exists(assetsPath))
            {
                using var document = JsonDocument.Parse(File.ReadAllBytes(assetsPath));
                var root = document.RootElement;
                if (root.TryGetProperty("project", out var projectJson) &&
                    projectJson.TryGetProperty("frameworks", out var frameworks) &&
                    frameworks.ValueKind == JsonValueKind.Object)
                {
                    foreach (var framework in frameworks.EnumerateObject())
                    {
                        if (!MatchesTargetFramework(framework.Name, targetFramework)) continue;
                        if (framework.Value.TryGetProperty("frameworkReferences", out var references) &&
                            references.ValueKind == JsonValueKind.Object)
                        {
                            foreach (var reference in references.EnumerateObject())
                                frameworkNames.Add(reference.Name);
                        }
                    }
                }
            }

            if (frameworkNames.Count == 0)
                frameworkNames.Add("Microsoft.NETCore.App");

            // The shared framework assemblies themselves are not embedded (~106 MB); only their names
            // are, which is all this method needs in order to decide copy-local suppression.
            foreach (var frameworkName in frameworkNames)
            {
                try
                {
                    names.UnionWith(EmbeddedSdkRefs.GetSharedFrameworkAssemblyNames(frameworkName));
                }
                catch (FileNotFoundException)
                {
                    // A framework with no embedded name list (e.g. an SDK workload) contributes nothing.
                }
            }
        }
        catch
        {
            // Fall back to only the base runtime pack if the assets file cannot be read.
            names.UnionWith(EmbeddedSdkRefs.GetSharedFrameworkAssemblyNames("Microsoft.NETCore.App"));
        }
        return names;
    }

    // "net10.0", "net10.0-windows", "netcoreapp3.1" -> "10.0"/"3.1" so the matching installed
    // shared framework version folder (e.g. "10.0.11") is selected.
    private static bool FrameworkFolderMatches(string folderPath, string targetFramework)
    {
        var numeric = new string(targetFramework.SkipWhile(c => !char.IsDigit(c)).TakeWhile(c => char.IsDigit(c) || c == '.').ToArray());
        var parts = numeric.Split('.');
        if (parts.Length < 2) return true; // unknown shape: accept and rely on the folder name
        var folderName = Path.GetFileName(folderPath);
        return folderName.StartsWith(parts[0] + "." + parts[1] + ".", StringComparison.Ordinal);
    }

    private static bool MatchesTargetFramework(string assetFramework, string projectFramework)
    {
        if (string.Equals(assetFramework, projectFramework, StringComparison.OrdinalIgnoreCase)) return true;
        // Asset entries can be fully-qualified (e.g. "net10.0"), while a project may multi-target;
        // match by the numeric version shape only as a fallback.
        return FrameworkFolderMatches(assetFramework + ".0", projectFramework);
    }

    // FEATURE: <Reference HintPath="..."> support. Real MSBuild resolves these (often property-driven,
    // e.g. `$(PkgMicrosoft_NET_ILLink_Tasks)\analyzers\...`); the native compiler previously only
    // handled ProjectReference/PackageReference items, so projects referencing DLLs by HintPath (like
    // NativeCompiler.csproj itself, via the ILLink/Roslyn generator analyzers) failed to compile under
    // self-hosting. Only the analyzer/SDK property tokens this codebase actually uses are expanded;
    // anything else is skipped rather than emulating MSBuild property evaluation.
    private static void CollectHintPathReferences(XML.Project xml, string projectRootPath,
        HashSet<string> referenceFiles)
    {
        foreach (var itemGroup in xml.ItemGroup)
        {
            foreach (var reference in itemGroup.References)
            {
                var hintPath = reference.HintPath;
                if (string.IsNullOrEmpty(hintPath)) continue;

                // The ILLink analyzers come from the embedded payload rather than the NuGet cache, and they are not
    // laid out as a package, so the package-relative path is rewritten to the payload directory before
    // the generic property tokens are expanded.
                var expanded = hintPath
                    .Replace(@"$(PkgMicrosoft_NET_ILLink_Tasks)\analyzers\dotnet\cs",
                        EmbeddedSdkRefs.IllinkAnalyzers)
                    .Replace(@"$(PkgMicrosoft_NET_ILLink_Tasks)/analyzers/dotnet/cs",
                        EmbeddedSdkRefs.IllinkAnalyzers)
                    .Replace("$(_NativeCompilerRefPackAnalyzersPath)", AsemblyExtensions.ResolveRefPackAnalyzersLocation)
                    .Replace("$(_NativeCompilerAspRefPackAnalyzersPath)", AsemblyExtensions.ResolveAspNetRefPackAnalyzersLocation)
                    .Replace("$(PkgMicrosoft_NET_ILLink_Tasks)", EmbeddedSdkRefs.SdkDirectory)
                    .Replace("$(MSBuildSDKsPath)", AsemblyExtensions.ResolveSdkMsBuildSdksPath)
                    .Replace('\\', Path.DirectorySeparatorChar)
                    .Replace('/', Path.DirectorySeparatorChar);
                if (string.IsNullOrEmpty(expanded)) continue;

                var filePath = Path.IsPathRooted(expanded)
                    ? Path.GetFullPath(expanded)
                    : Path.GetFullPath(Path.Combine(projectRootPath, expanded));

                if (File.Exists(filePath))
                    referenceFiles.Add(filePath);
            }
        }
    }

    private static List<string> GetTransitiveNugetPackages(string csprojPath, string? targetTfm)
    {
        var results = new List<string>();
        if (!File.Exists(csprojPath)) return results;

        var tfm = targetTfm ?? DefaultTargetFramework.Value;
        var xml = XML.Project.Parse(csprojPath);
        var packages = xml.ItemGroup.SelectMany(ig => ig.PackageReferences);

        foreach (var pkg in packages)
        {
            var pkgName = pkg.Include ?? "";
            var pkgVersion = pkg.Version
                ?? NuGetPackage.ResolveCentralVersion(pkgName, Path.GetDirectoryName(csprojPath) ?? "");
            if (string.IsNullOrEmpty(pkgName) || string.IsNullOrEmpty(pkgVersion)) continue;

            var pkgPath = NuGetPackage.FindPackagePath(pkgName, pkgVersion);
            if (string.IsNullOrEmpty(pkgPath)) continue;

            results.AddRange(NuGetPackage.FindPackageDLLs(pkgPath, tfm));
            results.AddRange(NuGetPackage.GetTransitivePackageDlls(pkgPath, tfm));
        }

        return results.Distinct(StringComparer.OrdinalIgnoreCase).ToList();
    }

    public static MetadataReference[] GetdefaultNugetReferences(Project project)
    {
        var referenceFiles = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        foreach (var (packageName, packageVersion, packagePath) in ResolvePackageReferences(project))
        {
            if (packagePath is null) continue;

            foreach (var dll in NuGetPackage.FindPackageDLLs(packagePath, project.TargetFramework ?? DefaultTargetFramework.Value))
                referenceFiles.Add(dll);

            foreach (var dll in NuGetPackage.GetTransitivePackageDlls(packagePath, project.TargetFramework ?? DefaultTargetFramework.Value))
                referenceFiles.Add(dll);
        }

        return referenceFiles
            .Select(path => (MetadataReference)MetadataReference.CreateFromFile(path))
            .ToArray();
    }

    // Single place where a PackageReference becomes a version and a directory on disk, so the
    // reference collection and the diagnostics below can never disagree about what resolved.
    private static IEnumerable<(string Name, string Version, string? Path)> ResolvePackageReferences(Project project)
    {
        foreach (var item in project.PackageReferences)
        {
            var packageName = item.Include ?? "";
            var packageVersion = item.Version ?? NuGetPackage.ResolveCentralVersion(packageName, project.ProjectRootPath);
            if (string.IsNullOrEmpty(packageName)) continue;

            yield return (packageName, packageVersion ?? "",
                string.IsNullOrEmpty(packageVersion)
                    ? null
                    : NuGetPackage.FindPackagePath(packageName, packageVersion));
        }
    }

    // A PackageReference that cannot be satisfied used to be skipped in silence, surfacing later
    // as a confusing CS0246 about a type from a package the user never mentioned. Naming the
    // package is the whole point of this.
    public static IReadOnlyList<string> GetUnresolvedPackageWarnings(Project project)
    {
        var warnings = new List<string>();

        foreach (var (packageName, packageVersion, packagePath) in ResolvePackageReferences(project))
        {
            if (string.IsNullOrEmpty(packageVersion))
            {
                warnings.Add(
                    $"NU1002: Unable to find package '{packageName}'. No version was specified on the " +
                    "PackageReference and no central PackageVersion entry was found in a Directory.Packages.props file.");
                continue;
            }

            if (packagePath is null)
            {
                warnings.Add(
                    $"NU1001: Package '{packageName}' version '{packageVersion}' was not found in the global " +
                    "packages folder. Run 'NativeCompilerCLI restore' to download it.");
            }
        }

        return warnings;
    }

    public static CSharpCompilationOptions GetCompilationOptions(Project project)
    {
        IEnumerable<string> Namespaces = new[]
        {
            "System",
        };

        IEnumerable<string> DefaultNamespacesWithGloBalUsingsForTopLevelExe = new[]
        {
            "System",
            //"global using global::System;",
            //"global using global::System.Collections.Generic;",
            //"global using global::System.IO;",
            //"global using global::System.Linq;",
            //"global using global::System.Net.Http;",
            //"global using global::System.Threading;",
            //"global using global::System.Threading.Tasks;",
        };

        var OutputKind = project.ResolvedProjectOutputKind();

        var DefaultNamespaces = OutputKind == OutputKind.ConsoleApplication
            ? DefaultNamespacesWithGloBalUsingsForTopLevelExe
            : Namespaces;

        // Roslyn's default ModuleName is "<asm>.exe" for Exe output kinds, but csc/MSBuild
        // embed the actual output filename ("<asm>.dll" for both console and web, the apphost
        // is a separate artifact). Mirror that so the module-definition name matches the SDK.
        // deterministic: true mirrors csc(/deterministic): binary-identical output for identical
        // input (reproducible PE timestamp, MVID and PDB id). HIGH_ENTROPY_VA (any CPU) is set
        // on EmitOptions in this Roslyn fork, not here.
        var DefaultCompilationOptions =
            new CSharpCompilationOptions(OutputKind, moduleName: project.ProjectName + ".dll",
                deterministic: true)
                .WithOptimizationLevel(OptimizationLevel.Debug)
                .WithUsings(DefaultNamespaces)
                .WithAllowUnsafe(project.AllowUnsafeBlocks);

        if (project.Nullable?.Contains("enable", StringComparison.OrdinalIgnoreCase) ?? false)
            DefaultCompilationOptions = DefaultCompilationOptions.WithNullableContextOptions(NullableContextOptions.Enable);

        return DefaultCompilationOptions;
    }

    // Mirrors NuGet's framework-assembly suppression: assemblies that are inbox in the runtime/ref pack
    // are dropped from package/project references so duplicate simple names (e.g. System.Collections.Immutable)
    // do not produce conflicting references.
    public static MetadataReference[] MergeFrameworkSuppression(
        IEnumerable<MetadataReference> nugetAndLocal,
        IEnumerable<MetadataReference> frameworkReferences)
    {
        var frameworkNames = new HashSet<string>(
            frameworkReferences.Select(reference =>
                Path.GetFileNameWithoutExtension(reference.Display) ?? ""),
            StringComparer.OrdinalIgnoreCase);

        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var merged = new List<MetadataReference>();

        foreach (var reference in nugetAndLocal)
        {
            var name = Path.GetFileNameWithoutExtension(reference.Display) ?? "";
            if (name.Length == 0) continue;
            if (frameworkNames.Contains(name)) continue;
            if (!seen.Add(name)) continue;
            merged.Add(reference);
        }

        merged.AddRange(frameworkReferences);
        return merged.ToArray();
    }

    public static void ThrowErrors(EmitResult result)
    {
        var errors = new List<string>();

        var failures = result.Diagnostics.Where(diagnostic =>
            diagnostic.IsWarningAsError ||
            diagnostic.Severity == DiagnosticSeverity.Error);

        foreach (var diagnostic in failures)
            errors.Add($"{diagnostic.Location} {diagnostic.Id}: {diagnostic.GetMessage()}");

        throw new Exception(string.Join("\n", errors));
    }

    private static readonly HashSet<string> GeneratedDirectoryNames = new(StringComparer.OrdinalIgnoreCase)
    {
        "bin", "obj", "myc", "sharpbin", "TestResults", ".vs", ".idea"
    };

    public static string[] ReadAllProjectFilesPath(string projectPath)
    {
        // Respect the project's own compile items. Real MSBuild starts from a default
        // **/*.cs glob (unless <EnableDefaultItems>false</EnableDefaultItems>) and refines it
        // with explicit <Compile Include>/<Compile Remove> items. Without this, template projects
        // (e.g. OrchardCore.ProjectTemplates, which disables default items and packs its *.cs
        // under content/ as None) accidentally compile files that must not be compiled.
        // Without a project file in this directory there is no project here to compile, and globbing
        // anyway silently swept in every .cs beneath it: building a repository root compiled sibling
        // projects' sources under whichever project's properties were picked, which surfaced as
        // unrelated diagnostics such as SYSLIB1062. Returning nothing keeps the failure local.
        var csprojFile = Directory.EnumerateFiles(projectPath, "*.csproj", SearchOption.TopDirectoryOnly)
            .FirstOrDefault();
        if (csprojFile is null) return Array.Empty<string>();

        var allFiles = EnumerateProjectSourceFiles(projectPath).ToList();

        XML.Project xml;
        try { xml = XML.Project.Parse(csprojFile); }
        catch { return allFiles.ToArray(); }

        var defaultItemsEnabled = !(xml.PropertyGroup?.FirstOrDefault()?.EnableDefaultItems
            ?.Trim().Equals("false", StringComparison.OrdinalIgnoreCase) ?? false);

        var compileIncludes = xml.ItemGroup.SelectMany(itemGroup => itemGroup.CompileItems)
            .Select(item => item.Include).Where(include => !string.IsNullOrWhiteSpace(include)).Select(include => include!).ToList();
        var compileRemoves = xml.ItemGroup.SelectMany(itemGroup => itemGroup.CompileItems)
            .Select(item => item.Remove).Where(remove => !string.IsNullOrWhiteSpace(remove)).Select(remove => remove!).ToList();
        var noneIncludes = xml.ItemGroup.SelectMany(itemGroup => itemGroup.NoneItems)
            .Select(item => item.Include).Where(include => !string.IsNullOrWhiteSpace(include)).Select(include => include!).ToList();

        IEnumerable<string> selected = defaultItemsEnabled ? allFiles : Enumerable.Empty<string>();
        if (!defaultItemsEnabled && compileIncludes.Count > 0)
            selected = MatchesAnyGlob(compileIncludes, allFiles, projectPath);
        else if (compileIncludes.Count > 0)
            selected = selected.Concat(MatchesAnyGlob(compileIncludes, allFiles, projectPath)).Distinct(StringComparer.OrdinalIgnoreCase);

        // Compile items may link files outside the project tree (e.g. OrchardCore.Setup includes
        // "..\OrchardCore.Localization\ModularPoFileLocationProvider.cs" with a Link). Such files
        // are not part of the local **/*.cs glob, so resolve each non-glob include to its absolute
        // path and add it when it exists on disk (mirrors MSBuild compiling the linked item).
        selected = selected.Concat(ResolveExternalCompileIncludes(compileIncludes, projectPath))
            .Distinct(StringComparer.OrdinalIgnoreCase);

        // None items and Compile Remove both take files out of the compile set.
        var removed = new HashSet<string>(
            MatchesAnyGlob(compileRemoves.Concat(noneIncludes).ToList(), allFiles, projectPath),
            StringComparer.OrdinalIgnoreCase);

        return selected.Where(file => !removed.Contains(file)).Concat(new[] { csprojFile })
            .Distinct(StringComparer.OrdinalIgnoreCase).ToArray();
    }

    // Simple glob over absolute file paths against patterns resolved from the project directory.
    // Supports **, * and ?. Patterns use MSBuild-style '/' separators; matching is case-insensitive.
    private static IEnumerable<string> MatchesAnyGlob(List<string> patterns, List<string> files, string projectPath)
    {
        if (patterns.Count == 0) return Enumerable.Empty<string>();

        var matchers = new List<string>();
        foreach (var pattern in patterns)
        {
            var replaced = pattern.Replace('\\', Path.DirectorySeparatorChar).Replace('/', Path.DirectorySeparatorChar);
            var full = Path.IsPathRooted(replaced)
                ? Path.GetFullPath(replaced)
                : Path.GetFullPath(Path.Combine(projectPath, replaced));
            matchers.Add(full.TrimEnd(Path.DirectorySeparatorChar) + Path.DirectorySeparatorChar);
        }

        return files.Where(file =>
        {
            var full = Path.GetFullPath(file);
            foreach (var matcher in matchers)
            {
                if (GlobMatch(full, matcher)) return true;
            }
            return false;
        });
    }

    // Resolves Compile Include items that point at a concrete file outside the project directory
    // (e.g. linked files introduced via "..\..\otherproject\File.cs"). Non-glob includes that exist
    // on disk are returned as absolute paths so they compile even though they are outside the
    // local **/*.cs enumeration. Glob includes (containing * or ?) stay unresolved here because
    // they can only span the local tree.
    private static IEnumerable<string> ResolveExternalCompileIncludes(List<string> compileIncludes, string projectPath)
    {
        foreach (var include in compileIncludes)
        {
            var replaced = include.Replace('\\', Path.DirectorySeparatorChar).Replace('/', Path.DirectorySeparatorChar);
            if (replaced.Contains('*') || replaced.Contains('?')) continue;

            var full = Path.IsPathRooted(replaced)
                ? Path.GetFullPath(replaced)
                : Path.GetFullPath(Path.Combine(projectPath, replaced));

            if (File.Exists(full))
                yield return full;
        }
    }

    // MSBuild-style glob over full paths: '**' is any run of characters (including '/'), '*' a single
    // path segment, '?' a single character. Matching is case-insensitive (paths come from the project
    // tree; MSBuild globs are case-insensitive on Windows and patterns originated there).
    private static bool GlobMatch(string path, string pattern)
    {
        var target = (path + Path.DirectorySeparatorChar).Replace(Path.DirectorySeparatorChar, '/');
        var pat = pattern.Replace(Path.DirectorySeparatorChar, '/');
        var regex =
            "^" + System.Text.RegularExpressions.Regex.Escape(pat)
                .Replace("\\*\\*", ".*")
                .Replace("\\*", "[^/]*")
                .Replace("\\?", "[^/]") + "$";
        return System.Text.RegularExpressions.Regex.IsMatch(target, regex,
            System.Text.RegularExpressions.RegexOptions.IgnoreCase);
    }

    private static IEnumerable<string> EnumerateProjectSourceFiles(string directory)
    {
        foreach (var file in Directory.EnumerateFiles(directory, "*.*", SearchOption.TopDirectoryOnly))
        {
            var extension = Path.GetExtension(file);
            if (extension.Equals(".cs", StringComparison.OrdinalIgnoreCase)
                || extension.Equals(".csproj", StringComparison.OrdinalIgnoreCase))
            {
                yield return file;
            }
        }

        foreach (var subDirectory in Directory.EnumerateDirectories(directory, "*.*", SearchOption.TopDirectoryOnly))
        {
            if (GeneratedDirectoryNames.Contains(Path.GetFileName(subDirectory)))
                continue;
            foreach (var file in EnumerateProjectSourceFiles(subDirectory))
                yield return file;
        }
    }


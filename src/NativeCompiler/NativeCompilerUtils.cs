    // ---------------------------------------------------------------------------
    // Feature: package buildTransitive/build <Using> global usings.
    // NuGet packages can ship .props (e.g. Parlot's buildTransitive/Parlot.props) that inject
    // global usings into consuming projects (<Using Include="X" Static="true" />). The real SDK
    // consumes these items when generating the implicit GlobalUsings file. General (no
    // provider-specific types). DELETABLE FEATURE.
    // ---------------------------------------------------------------------------
    public static string BuildPackageUsingStatements(Project project)
    {
        var result = new StringBuilder();
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var tfm = project.TargetFramework ?? DefaultTargetFramework.Value;

        void AddUsing(NuGetPackage.PackageUsingItem item)
        {
            var key = (item.Static ? "static " : "") + item.Namespace;
            if (!seen.Add(key)) return;
            result.Append("global using ");
            if (item.Static) result.Append("static ");
            result.Append("global::").Append(item.Namespace).AppendLine(";");
        }

        foreach (var packageItem in project.PackageReferences)
        {
            var packageName = packageItem.Include ?? "";
            var packageVersion = packageItem.Version ??
                NuGetPackage.ResolveCentralVersion(packageName, project.ProjectRootPath);
            if (string.IsNullOrEmpty(packageName) || string.IsNullOrEmpty(packageVersion)) continue;

            var packagePath = NuGetPackage.FindPackagePath(packageName, packageVersion);
            if (string.IsNullOrEmpty(packagePath)) continue;

            foreach (var item in NuGetPackage.ReadPackageUsingItems(packagePath)) AddUsing(item);
            foreach (var transitivePath in NuGetPackage.GetTransitivePackagePaths(packagePath, tfm))
                foreach (var item in NuGetPackage.ReadPackageUsingItems(transitivePath)) AddUsing(item);
        }

        return result.ToString();
    }

    public static Project GetProjectDetails(List<ProjectFile> projectFiles, string projectRootPath)
    {
        var CsProjFile = projectFiles.FirstOrDefault(item => Path.GetExtension(item.FilePath) == ".csproj")
                         ?? throw new ArgumentException("Project does not have csproject file");

        var CSFiles = projectFiles.Where(item => Path.GetExtension(item.FilePath) == ".cs").ToList()
                      ?? throw new ArgumentException("Project does not have c sharp files");

        var project = new Project(CsProjFile, CSFiles, projectRootPath);

        // Web SDK projects import Microsoft.NET.Sdk.Web, which adds its own implicit usings
        // (Microsoft.AspNetCore.*) on top of the base net SDK set. Without them WebApplication
        // etc. fail (CS0103). Kept general (no provider-specific types). DELETABLE FEATURE.
        var globalUsingFile =
        """
        // <auto-generated/>
        global using System;
        global using System.Collections.Generic;
        global using System.IO;
        global using System.Linq;
        global using System.Net.Http;
        global using System.Threading;
        global using System.Threading.Tasks;
        """;

        if (project.IsWebSdk)
        {
            // Web SDK order mirrors the SDK's generated {Name}.GlobalUsings.g.cs: the ASP.NET Core
            // group first, then the base set with System.Net.Http.Json added.
            globalUsingFile =
            """
            // <auto-generated/>
            global using Microsoft.AspNetCore.Builder;
            global using Microsoft.AspNetCore.Hosting;
            global using Microsoft.AspNetCore.Http;
            global using Microsoft.AspNetCore.Routing;
            global using Microsoft.Extensions.Configuration;
            global using Microsoft.Extensions.DependencyInjection;
            global using Microsoft.Extensions.Hosting;
            global using Microsoft.Extensions.Logging;
            global using System;
            global using System.Collections.Generic;
            global using System.IO;
            global using System.Linq;
            global using System.Net.Http;
            global using System.Net.Http.Json;
            global using System.Threading;
            global using System.Threading.Tasks;
            """;
        }

        // NuGet packages can ship buildTransitive/build .props with <Using> items (e.g. Parlot)
        // that inject extra global usings into consuming projects. DELETABLE FEATURE.
        var packageUsings = BuildPackageUsingStatements(project);

        // The SDK materializes its synthesized sources at obj/<config>/<tfm>/, and uses those
        // paths for the PDB documents too. Mirroring name + path keeps the PDB document set
        // (names and SHA-1 checksums) equal to `dotnet build` output.
        var identity = BuildPropsEvaluator.EvaluateIdentity(project.ProjectRootPath);
        var configuration = identity?.Configuration ?? "Debug";
        var generatedRoot = GetGeneratedFileRoot(project, configuration);

        if (project.ImplicitUsings)
        {
            project.CSFiles.Add(new ProjectFile(Path.Combine(generatedRoot, project.ProjectName + ".GlobalUsings.g.cs"), globalUsingFile + "\n" + packageUsings));
        }
        else if (!string.IsNullOrWhiteSpace(packageUsings))
        {
            project.CSFiles.Add(new ProjectFile(Path.Combine(generatedRoot, project.ProjectName + ".GlobalUsings.g.cs"), packageUsings));
        }

        //Todo read from csproj and add this file currently will be ignored
        // Only inject assembly attributes when the project does not declare any itself
        // (projects with their own AssemblyInfo.cs / [assembly:] attributes will have duplicates).
        // Values mirror the SDK's GenerateAssemblyInfo defaults so produced assemblies carry the
        // same identity attributes as `dotnet build` output (parity): Company/Product/Title fall
        // back to the assembly name, versioning to $(Version) / $(AssemblyVersion) etc., and the
        // informational version appends the SourceRevisionId only when one is evaluated.
        var hasExistingAssemblyAttributes = project.CSFiles.Any(item => item.FileContent.Contains("[assembly:", StringComparison.OrdinalIgnoreCase));

        var assemblyName = project.ProjectName;
        var company = identity?.Company ?? assemblyName;
        var product = identity?.Product ?? assemblyName;
        var title = identity?.Title ?? assemblyName;
        var version = identity?.Version ?? "1.0.0";
        // The SDK pads an unset AssemblyVersion to four parts ("1.0.0" becomes "1.0.0.0"),
        // matching the AssemblyVersion attribute in its generated AssemblyInfo.cs.
        var assemblyVersion = identity?.AssemblyVersion ?? PadToFourParts(version);
        // SDK pads the file version to four parts ("1.0.0" becomes "1.0.0.0"), matching the
        // AssemblyFileVersion attribute csc emits for a default $(Version).
        var fileVersion = identity?.FileVersion ?? PadToFourParts(assemblyVersion);
        var informationalVersion = identity?.InformationalVersion
            ?? version + (string.IsNullOrEmpty(identity?.SourceRevisionId) ? "" : "+" + identity!.SourceRevisionId);

        var targetFramework = project.TargetFramework ?? DefaultTargetFramework.Value;
        var tfmVersion = targetFramework.StartsWith("net", StringComparison.Ordinal) ? targetFramework[3..] : targetFramework;

        // The SDK emits the TargetFramework attribute into its own generated file
        // (obj/<config>/<tfm>/.NETCoreApp,Version=v<tf>.AssemblyAttributes.cs). The content
        // mirrors the SDK's byte-for-byte (including the unconventional "// <autogenerated />"
        // header) so the PDB document checksum equals `dotnet build` output.
        var targetFrameworkSource =
        $"""
        // <autogenerated />
        using System;
        using System.Reflection;
        [assembly: global::System.Runtime.Versioning.TargetFrameworkAttribute(".NETCoreApp,Version=v{tfmVersion}", FrameworkDisplayName = ".NET {tfmVersion}")]
        """ + "\n";

        project.CSFiles.Add(new ProjectFile(Path.Combine(generatedRoot, $".NETCoreApp,Version=v{tfmVersion}.AssemblyAttributes.cs"), targetFrameworkSource));

        if (!hasExistingAssemblyAttributes)
        {
            // Mirrors the SDK's generated AssemblyInfo.cs (WriteCodeFragment output) byte-for-byte
            // so the PDB document checksum equals `dotnet build` output.
            var assemblyInfoSource =
            $"""
            //------------------------------------------------------------------------------
            // <auto-generated>
            //     This code was generated by a tool.
            //
            //     Changes to this file may cause incorrect behavior and will be lost if
            //     the code is regenerated.
            // </auto-generated>
            //------------------------------------------------------------------------------

            using System;
            using System.Reflection;

            [assembly: System.Reflection.AssemblyCompanyAttribute({CSharpStringLiteral(company)})]
            [assembly: System.Reflection.AssemblyConfigurationAttribute({CSharpStringLiteral(configuration)})]
            [assembly: System.Reflection.AssemblyFileVersionAttribute({CSharpStringLiteral(fileVersion)})]
            [assembly: System.Reflection.AssemblyInformationalVersionAttribute({CSharpStringLiteral(informationalVersion)})]
            [assembly: System.Reflection.AssemblyProductAttribute({CSharpStringLiteral(product)})]
            [assembly: System.Reflection.AssemblyTitleAttribute({CSharpStringLiteral(title)})]
            [assembly: System.Reflection.AssemblyVersionAttribute({CSharpStringLiteral(assemblyVersion)})]

            // Generated by the MSBuild WriteCodeFragment class.

            """ + "\n";
            project.CSFiles.Add(new ProjectFile(Path.Combine(generatedRoot, $"{project.ProjectName}.AssemblyInfo.cs"), assemblyInfoSource));
        }

        // <InternalsVisibleTo Include="..." /> (and AssemblyAttribute InternalsVisibleTo) items make
        // internal members visible to named friend assemblies. Real MSBuild flattens both into
        // generated [assembly: InternalsVisibleTo] attributes; without them projects like
        // OrchardCore fail with CS1061/CS0122 on internal members of their references. Names the
        // project already emits in its own source (Properties\AssemblyInfo.cs) are skipped so
        // duplicate attributes do not trip CS0579.
        var existingIvT = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var item in project.CSFiles)
        {
            foreach (System.Text.RegularExpressions.Match match in System.Text.RegularExpressions.Regex.Matches(
                item.FileContent, @"InternalsVisibleTo\(\s*""(?<name>[^""]+)""", System.Text.RegularExpressions.RegexOptions.IgnoreCase))
            {
                if (match.Groups["name"].Success)
                    existingIvT.Add(match.Groups["name"].Value.Trim());
            }
        }

        var ivtSource = new StringBuilder();
        foreach (var name in project.InternalsVisibleToNames.Distinct(StringComparer.OrdinalIgnoreCase))
        {
            if (existingIvT.Contains(name)) continue;
            ivtSource.AppendLine($"[assembly: System.Runtime.CompilerServices.InternalsVisibleTo(\"{name}\")]");
        }

        if (ivtSource.Length > 0)
            project.CSFiles.Add(new ProjectFile("InternalsVisibleTo.g.cs", ivtSource.ToString()));

        // Aspire AppHost SDK generates Projects.<ClassName> metadata classes at build time through
        // MSBuild targets (Aspire.Hosting.AppHost.targets: CreateAspireProjectMetadataSources +
        // CreateAspireHostProjectMetadataSources), not a Roslyn source generator. Those <Compile>
        // items never reach us, so synthesize the two generated files the same way MSBuild does:
        // one class per project resource (implements IProjectMetadata) plus the host's own class.
        if (project.IsAspireHost)
        {
            var aspireMetadata = new StringBuilder();

            // The regex the targets use to derive a C# class name from a project file name:
            // replace every non-word char with '_', and prepend '_' for a digit at start or right
            // after a '.', e.g. OrchardCore.Cms.Web -> OrchardCore_Cms_Web.
            string AspireClassName(string projectFileName)
            {
                // The targets' regex: (((?<=\.)|^)(?=\d)|\W) -> '_', i.e. prefix a digit at start
                // or right after a '.', and replace every non-word char (including '.') with '_'.
                // OrchardCore.Cms.Web -> OrchardCore_Cms_Web.
                var name = Path.GetFileNameWithoutExtension(projectFileName);
                var result = new System.Text.StringBuilder();
                for (var i = 0; i < name.Length; i++)
                {
                    var ch = name[i];
                    var prev = i > 0 ? name[i - 1] : '\0';
                    if (char.IsDigit(ch) && (i == 0 || prev == '.'))
                        result.Append('_');
                    if (char.IsLetterOrDigit(ch) || ch == '_') result.Append(ch);
                    else result.Append('_');
                }
                return result.ToString();
            }

            string ProjectPathFor(string include)
            {
                var normalized = include.Replace('\\', Path.DirectorySeparatorChar)
                    .Replace('/', Path.DirectorySeparatorChar);
                var full = Path.GetFullPath(Path.Combine(project.ProjectRootPath, normalized));
                return Path.TrimEndingDirectorySeparator(full) switch
                {
                    var p when Directory.Exists(p) => p,
                    var p => Path.GetDirectoryName(p) ?? p,
                };
            }

            // The host itself (used by AddProject<T> via its static ProjectPath).
            var hostClass = AspireClassName(CsProjFile.FilePath);
            var hostPath = Path.TrimEndingDirectorySeparator(project.ProjectRootPath);
            aspireMetadata.AppendLine("// <auto-generated/>");
            aspireMetadata.AppendLine();
            aspireMetadata.AppendLine("namespace Projects;");
            aspireMetadata.AppendLine();
            aspireMetadata.AppendLine("#pragma warning disable CS8981");
            aspireMetadata.AppendLine("/// <summary>");
            aspireMetadata.AppendLine("/// Metadata for the Aspire AppHost project.");
            aspireMetadata.AppendLine("/// </summary>");
            aspireMetadata.AppendLine("[global::System.CodeDom.Compiler.GeneratedCode(\"Aspire.Hosting\", null)]");
            aspireMetadata.AppendLine("[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage(Justification = \"Generated code.\")]");
            aspireMetadata.AppendLine($"[global::System.Diagnostics.DebuggerDisplay(\"Type = {{GetType().Name,nq}}, ProjectPath = {{ProjectPath}}\")]");
            aspireMetadata.AppendLine($"internal class {hostClass}");
            aspireMetadata.AppendLine("#pragma warning restore CS8981");
            aspireMetadata.AppendLine("{");
            aspireMetadata.AppendLine($"    private {hostClass}() {{ }}");
            aspireMetadata.AppendLine();
            aspireMetadata.AppendLine("    /// <summary>");
            aspireMetadata.AppendLine("    /// The path to the Aspire Host project.");
            aspireMetadata.AppendLine("    /// </summary>");
            aspireMetadata.AppendLine($"    public static string ProjectPath => \"\"\"{hostPath}\"\"\";");
            aspireMetadata.AppendLine("}");
            aspireMetadata.AppendLine();

            foreach (var reference in project.ProjectReferences)
            {
                var include = reference.Include ?? "";
                if (string.IsNullOrWhiteSpace(include)) continue;
                var className = AspireClassName(include);
                var projectPath = ProjectPathFor(include);
                aspireMetadata.AppendLine("/// <summary>");
                aspireMetadata.AppendLine($"/// Metadata for the {className} project.");
                aspireMetadata.AppendLine("/// </summary>");

        [assembly: System.Reflection.AssemblyProductAttribute("MSCompiler")]
        [assembly: System.Reflection.AssemblyTitleAttribute("MSCompiler")]
        [assembly: System.Reflection.AssemblyVersionAttribute("1.0.0.0")]
